/**
 * Helper function that automatically syncs equipment files, calibration records,
 * failure logs, and maintenance tasks into the documents library!
 */
export function generateAutoSyncedDocuments(
  equipmentList: EquipmentItem[] = [],
  calibrationsList: CalibrationRecord[] = [],
  failuresList: FailureReport[] = [],
  tasksList: TaskEvent[] = [],
  _purchaseRequests: PurchaseRequest[] = []
): HospitalDocumentFile[] {
  const syncedFiles: HospitalDocumentFile[] = [];

  // 1. Calibration Records Auto-Sync
  calibrationsList.forEach((cal) => {
    // Determine appropriate folder
    let targetFolderId = 'fld-root-calibration';
    const dept = cal.department?.toLowerCase() || '';
    if (dept.includes('اورژانس') || dept.includes('emergency')) {
      targetFolderId = 'fld-cal-emergency';
    } else if (dept.includes('icu') || dept.includes('ccu') || dept.includes('ویژه')) {
      targetFolderId = 'fld-cal-icu';
    } else if (dept.includes('عمل') || dept.includes('or') || dept.includes('surgery')) {
      targetFolderId = 'fld-cal-or';
    }

    const isPassed = cal.finalResult === 'pass' || cal.finalResult === 'conditional_pass';
    const sizeBytes = 1800000 + (cal.id.length * 35000) % 1500000;
    const sizeFormatted = (sizeBytes / (1024 * 1024)).toFixed(2) + ' مگابایت';

    syncedFiles.push({
      id: `doc-sync-cal-${cal.id}`,
      folderId: targetFolderId,
      title: `گواهی کالیبراسیون ${cal.equipmentName} (${cal.equipmentCode}) - دوره ${cal.issueDate}`,
      originalFileName: `Cert_Calibration_${cal.equipmentCode}_${cal.certNumber || 'Auto'}.pdf`,
      extension: 'pdf',
      fileSizeBytes: sizeBytes,
      fileSizeFormatted: sizeFormatted,
      category: 'calibration',
      isAutoGenerated: true,
      sourceRecordType: 'calibration',
      sourceRecordId: cal.id,
      equipmentCode: cal.equipmentCode,
      equipmentName: cal.equipmentName,
      department: cal.department,
      uploadDate: cal.issueDate,
      uploadedByName: cal.inspector || 'کارشناس کالیبراسیون',
      uploadedByRoleFa: 'سیستم ثبت خودکار کالیبراسیون',
      isStarred: !isPassed,
      tags: ['گواهی کالیبراسیون', isPassed ? 'تایید شده' : 'نیازمند تنظیم', cal.department || 'بیمارستان'],
      description: `شماره گواهی: ${cal.certNumber || 'CAL-1403-AUTO'} | مرجع صدور: ${cal.agency || 'آزمایشگاه مرجع'} | نتیجه آزمون: ${isPassed ? 'قبول' : 'مردود/مشروط'} | تاریخ انقضا: ${cal.expiryDate}`,
      version: '1.0',
    });
  });

  // 2. Failure Reports Auto-Sync
  failuresList.forEach((fail) => {
    const sizeBytes = 1200000 + (fail.id.length * 28000) % 900000;
    const sizeFormatted = (sizeBytes / (1024 * 1024)).toFixed(2) + ' مگابایت';
    const isCritical = fail.priority === 'critical';

    syncedFiles.push({
      id: `doc-sync-fail-${fail.id}`,
      folderId: 'fld-root-failures',
      title: `گزارش ثبت خرابی و اقدام فنی ${fail.equipmentName} (${fail.equipmentCode}) - گزارش #${fail.reportNo}`,
      originalFileName: `Failure_Report_${fail.equipmentCode}_${fail.reportNo}.pdf`,
      extension: 'pdf',
      fileSizeBytes: sizeBytes,
      fileSizeFormatted: sizeFormatted,
      category: 'failures',
      isAutoGenerated: true,
      sourceRecordType: 'failure',
      sourceRecordId: fail.id,
      equipmentCode: fail.equipmentCode,
      equipmentName: fail.equipmentName,
      department: fail.department,
      uploadDate: fail.reportDate,
      uploadedByName: fail.reporterName || 'اپراتور بخش',
      uploadedByRoleFa: 'سیستم ثبت خرابی',
      isStarred: isCritical,
      tags: ['گزارش خرابی', `اولویت: ${isCritical ? 'حیاتی' : 'عادی'}`, fail.status === 'resolved' ? 'رفع نقص شده' : 'در دست اقدام'],
      description: `شرح نقص: ${fail.defectDescription || 'ثبت شده در سامانه'} | وضعیت رسیدگی: ${fail.status === 'resolved' ? 'رفع کامل نقص و تایید سلامت' : 'در حال تعمیر'} | ارجاع شده به: ${fail.technicianAssigned || 'مهندسی پزشکی'}`,
      version: '1.0',
    });
  });

  // 3. Maintenance and Repair Tasks Auto-Sync
  tasksList
    .filter((t) => t.type === 'maintenance' || t.type === 'daily_checklist')
    .forEach((task) => {
      const sizeBytes = 850000 + (task.id.length * 15000) % 600000;
      const sizeFormatted = (sizeBytes / (1024 * 1024)).toFixed(2) + ' مگابایت';

      syncedFiles.push({
        id: `doc-sync-task-${task.id}`,
        folderId: 'fld-rep-pm',
        title: `کاربرگ نگهداری و وظیفه: ${task.title}`,
        originalFileName: `Maintenance_Worksheet_${task.id}.docx`,
        extension: 'docx',
        fileSizeBytes: sizeBytes,
        fileSizeFormatted: sizeFormatted,
        category: 'repairs',
        isAutoGenerated: true,
        sourceRecordType: 'task',
        sourceRecordId: task.id,
        equipmentCode: task.equipmentCode,
        equipmentName: task.equipmentName,
        department: task.department,
        uploadDate: task.dueDate || '۱۴۰۳/۰۵/۰۱',
        uploadedByName: task.assignedTo || 'مسئول نگهداری',
        uploadedByRoleFa: 'کارشناس سرویس PM',
        tags: ['نگهداری پیشگیرانه', task.status === 'completed' ? 'تکمیل شده' : 'در جریان', task.type === 'daily_checklist' ? 'چک‌لیست روزانه' : 'سرویس PM'],
        description: `مسئول اقدام: ${task.assignedTo || 'معین'} | اولویت: ${task.priority} | توضیحات: ${task.notes || 'سرویس منظم دوره‌ای بر اساس استاندارد سازنده'}`,
        version: '1.0',
      });
    });

  // 4. Equipment Passport & Manuals Auto-Sync
  equipmentList.forEach((eq) => {
    const sizeBytes = 3500000 + (eq.id.length * 45000) % 4000000;
    const sizeFormatted = (sizeBytes / (1024 * 1024)).toFixed(2) + ' مگابایت';
    const equipTitle = eq.faName || eq.enName || 'تجهیز پزشکی';

    syncedFiles.push({
      id: `doc-sync-eq-${eq.id}`,
      folderId: 'fld-root-manuals',
      title: `شناسنامه فنی، کاتالوگ و راهنمای کاربری ${equipTitle} (${eq.model || eq.code})`,
      originalFileName: `Passport_Manual_${eq.code}_${eq.brand || 'Equip'}.pdf`,
      extension: 'pdf',
      fileSizeBytes: sizeBytes,
      fileSizeFormatted: sizeFormatted,
      category: 'equipment_manuals',
      isAutoGenerated: true,
      sourceRecordType: 'equipment',
      sourceRecordId: eq.id,
      equipmentCode: eq.code,
      equipmentName: equipTitle,
      department: eq.department,
      uploadDate: eq.purchaseDate || '۱۴۰۳/۰۱/۱۵',
      uploadedByName: 'سیستم ثبت خودکار اموال',
      uploadedByRoleFa: 'سیستم هوشمند اموال',
      tags: ['شناسنامه دستگاه', eq.brand || 'سازنده معتبر', eq.department || 'بیمارستان', eq.status],
      description: `شماره سریال: ${eq.serialNumber || 'SN-AUTO'} | کمپانی سازنده: ${eq.brand || 'استاندارد'} | مدل: ${eq.model || 'معین'} | وضعیت: ${eq.status}`,
      version: '1.0',
    });
  });

  return syncedFiles;
}
